create table public.leads (
  id bigint generated by default as identity primary key,
  source_row integer not null,
  name text not null,
  age integer,
  age_band text,
  phone text,
  email text,
  dob date,
  topics text[] not null default '{}',
  status text,
  struck boolean not null default false,
  first_captured date,
  remarks text,
  source_tabs text,
  import_batch text not null,
  created_at timestamptz not null default now(),
  constraint leads_import_row_unique unique (import_batch, source_row)
);

create index leads_age_band_idx on public.leads (age_band);
create index leads_status_idx on public.leads (status);
create index leads_email_idx on public.leads (email);
create index leads_topics_idx on public.leads using gin (topics);

create table public.campaigns (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  poster_name text,
  poster_path text,
  subject text not null,
  message text not null,
  audience jsonb not null default '{}'::jsonb,
  audience_count integer not null default 0,
  status text not null default 'draft'
    check (status in ('draft', 'queued', 'sending', 'sent', 'paused')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index campaigns_status_idx on public.campaigns (status);
create index campaigns_created_at_idx on public.campaigns (created_at desc);

create table public.campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  lead_id bigint not null references public.leads(id) on delete cascade,
  email text not null,
  status text not null default 'queued'
    check (status in ('queued', 'sent', 'failed', 'replied', 'paused')),
  created_at timestamptz not null default now(),
  constraint campaign_recipient_unique unique (campaign_id, lead_id)
);

create index campaign_recipients_campaign_idx on public.campaign_recipients (campaign_id);
create index campaign_recipients_status_idx on public.campaign_recipients (status);

alter table public.leads enable row level security;
alter table public.campaigns enable row level security;
alter table public.campaign_recipients enable row level security;

revoke all on table public.leads from anon, authenticated;
revoke all on table public.campaigns from anon, authenticated;
revoke all on table public.campaign_recipients from anon, authenticated;
revoke all on sequence public.leads_id_seq from anon, authenticated;
revoke all on sequence public.campaign_recipients_id_seq from anon, authenticated;

grant all on table public.leads to service_role;
grant all on table public.campaigns to service_role;
grant all on table public.campaign_recipients to service_role;
grant usage, select on sequence public.leads_id_seq to service_role;
grant usage, select on sequence public.campaign_recipients_id_seq to service_role;

