create table public.whatsapp_messages (
  id bigint generated by default as identity primary key,
  direction text not null check (direction in ('inbound', 'outbound')),
  lead_id bigint references public.leads(id) on delete set null,
  campaign_id uuid references public.campaigns(id) on delete set null,
  external_message_id text not null,
  chat_id text,
  sender_platform_id text,
  sender_phone text,
  recipient_phone text,
  sender_name text,
  body text not null,
  category text not null default 'Follow-up'
    check (category in ('Interested', 'Not Interested', 'Question', 'Out of Office', 'Follow-up', 'Unsubscribe')),
  read_at timestamptz,
  starred boolean not null default false,
  occurred_at timestamptz not null default now(),
  raw_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint whatsapp_messages_external_id_unique unique (external_message_id)
);

create index whatsapp_messages_direction_occurred_idx
  on public.whatsapp_messages (direction, occurred_at desc);
create index whatsapp_messages_lead_occurred_idx
  on public.whatsapp_messages (lead_id, occurred_at desc);
create index whatsapp_messages_campaign_idx
  on public.whatsapp_messages (campaign_id);
create index whatsapp_messages_sender_phone_idx
  on public.whatsapp_messages (sender_phone);

alter table public.whatsapp_messages enable row level security;

revoke all on table public.whatsapp_messages from anon, authenticated;
revoke all on sequence public.whatsapp_messages_id_seq from anon, authenticated;

grant all on table public.whatsapp_messages to service_role;
grant usage, select on sequence public.whatsapp_messages_id_seq to service_role;
