create table if not exists public.campaign_reminder_deliveries (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  lead_id bigint not null references public.leads(id) on delete cascade,
  reminder_at timestamptz not null,
  offset_hours integer not null check (offset_hours in (168, 24, 5)),
  status text not null default 'pending'
    check (status in ('pending', 'sending', 'sent', 'failed', 'skipped')),
  attempts integer not null default 0 check (attempts >= 0),
  next_attempt_at timestamptz default now(),
  locked_until timestamptz,
  external_message_id text,
  last_error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_reminder_delivery_unique
    unique (campaign_id, lead_id, reminder_at)
);

create index if not exists campaign_reminder_deliveries_due_idx
  on public.campaign_reminder_deliveries (status, next_attempt_at, reminder_at)
  where status in ('pending', 'failed', 'sending');

create index if not exists campaign_reminder_deliveries_campaign_idx
  on public.campaign_reminder_deliveries (campaign_id, reminder_at);

alter table public.campaign_reminder_deliveries enable row level security;

revoke all on table public.campaign_reminder_deliveries from public, anon, authenticated;
revoke all on sequence public.campaign_reminder_deliveries_id_seq from public, anon, authenticated;
grant all on table public.campaign_reminder_deliveries to service_role;
grant usage, select on sequence public.campaign_reminder_deliveries_id_seq to service_role;

create or replace function public.claim_campaign_reminder_deliveries(p_limit integer default 10)
returns setof public.campaign_reminder_deliveries
language plpgsql
security definer
set search_path = ''
as $$
begin
  return query
  with claimable as (
    select delivery.id
    from public.campaign_reminder_deliveries as delivery
    where (delivery.status in ('pending', 'failed')
        or (delivery.status = 'sending' and delivery.locked_until < now()))
      and delivery.attempts < 5
      and delivery.reminder_at <= now()
      and (delivery.next_attempt_at is null or delivery.next_attempt_at <= now())
      and (delivery.locked_until is null or delivery.locked_until < now())
    order by delivery.reminder_at, delivery.id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 10), 50))
  )
  update public.campaign_reminder_deliveries as delivery
  set status = 'sending',
      attempts = delivery.attempts + 1,
      locked_until = now() + interval '4 minutes',
      updated_at = now()
  from claimable
  where delivery.id = claimable.id
  returning delivery.*;
end;
$$;

revoke all on function public.claim_campaign_reminder_deliveries(integer) from public, anon, authenticated;
grant execute on function public.claim_campaign_reminder_deliveries(integer) to service_role;
